"""STEP 0, the mandatory single-column-sensitivity gate (PATH.md 0.1 / 7.3 C).

Harness: `experiments/rule30/p_geometric_attack/discriminator.py`, imported
READ-ONLY, using its `diagram`, `overwrite_centre` and `s0_control`.
  A = true Rule 30 lone-seed diagram
  B = A with column 0 overwritten by 0101..., nothing else changed
  C = true Rule 90 lone-seed diagram

Quantity under test (the class this arm searches): fix a finite monoid M with
identity e, a window width w, and a map phi: {0,1}^w -> M with phi(0^w) = e.
For a width-W window about the centre of row t,

    Phi_W(row) = phi(v_1) * phi(v_2) * ... * phi(v_W)      (left to right)

an element of M, NOT a number.  Its natural sensitivity metric is therefore
exact disagreement, not a difference of reals:

    disagree(W) = fraction of rows t in [T/2, T) with Phi_W(A_t) != Phi_W(B_t).

The column-0 positive control in the same metric is Q(row) = the centre bit;
`s0_control` from the mandated harness is reported alongside it as the
cross-check that the two agree on ~0.489.

PRE-REGISTERED PREDICTION, recorded before running.
  (P1) The non-abelian monoid product is NOT column-blind: disagree(W) is
       Omega(1) and FLAT in W, because in a group
       Phi_W(B) = L * (g^-1 g') * R with L, R the sub-products either side of
       the changed factor, and nothing in that expression shrinks with W.
  (P2) The a14 abelian site sum read EXACTLY (mod 2, unnormalised) is ALSO
       flat.  a14's O(1/W) came from its explicit 1/W normalisation, not from
       the algebra.
  (P3) The same site sum read as a NORMALISED real density decays like 1/W,
       reproducing a14 section 2.2/2.3.
KILL CONDITION: if the monoid product's disagree(W) decays like 1/W or faster
against the flat control, obstruction C retires the whole class and the arm
stops here without searching.  That is the outcome the arm was expected to
have; it is pre-registered as the kill so it can fire.
"""

from __future__ import annotations

import importlib.util
import json
import random
import sys

import numpy as np

sys.path.insert(0, "/Volumes/A/researchpapers/13-rule30/experiments/overnight-arms/"
                   "frontier_attack/a15_nonabelian_invariant")
from monoids import registry  # noqa: E402

DISC = ("/Volumes/A/researchpapers/13-rule30/experiments/rule30/"
        "p_geometric_attack/discriminator.py")


def load_discriminator():
    spec = importlib.util.spec_from_file_location("a15_discriminator", DISC)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def win_indices(vec, w):
    """Window indices over a 0/1 numpy row slice."""
    out = []
    n = len(vec)
    for x in range(n - w + 1):
        v = 0
        for j in range(w):
            v = (v << 1) | int(vec[x + j])
        out.append(v)
    return out


def make_monoid_stat(mon, w, phi):
    n, mul = mon.n, mon.mul

    def f(vec):
        r = 0
        for v in win_indices(vec, w):
            r = mul[r * n + phi[v]]
        return r

    return f


def make_mod2_sum(w, phi):
    def f(vec):
        return sum(phi[v] for v in win_indices(vec, w)) % 2

    return f


def make_density(w, phi):
    def f(vec):
        ws = win_indices(vec, w)
        return sum(phi[v] for v in ws) / len(ws)

    return f


def centre_bit(vec):
    return int(vec[len(vec) // 2])


def main():
    T = int(sys.argv[1]) if len(sys.argv) > 1 else 400
    disc = load_discriminator()
    B = T + 4
    A = disc.diagram(30, T, B)
    Bg = disc.overwrite_centre(A, B)
    C = disc.diagram(90, T, B)
    assert (A != Bg).sum() == (A[:, B] != Bg[:, B]).sum(), \
        "B must differ from A on column 0 only"
    ndiff = int((A[:, B] != Bg[:, B]).sum())

    reg = registry()
    rng = random.Random(30903)
    cands = []

    # --- positive control: reads column 0 only -----------------------------
    cands.append(("COL0_control_centre_bit", centre_bit, "exact"))

    # --- non-abelian monoid products (the class this arm searches) ---------
    for mname in ("S3", "T3", "T2", "FlipFlop3"):
        mon = reg[mname]
        for w in (2, 3):
            for k in range(2):
                phi = [0] * (1 << w)
                for v in range(1, 1 << w):
                    phi[v] = rng.randrange(mon.n)
                cands.append((f"NONAB_{mname}_w{w}_rand{k}",
                              make_monoid_stat(mon, w, phi), "exact"))
    # a structured one: phi sends the window to the transformation it induces
    # on 3 states, S3 generated by a transposition and a 3-cycle
    mon = reg["S3"]
    tr = mon.elems.index((1, 0, 2))
    cy = mon.elems.index((1, 2, 0))
    phi = [0, tr, cy, 0, cy, tr, tr, cy]  # w=3, phi(000)=e
    cands.append(("NONAB_S3_w3_structured", make_monoid_stat(mon, 3, phi), "exact"))

    # --- a14's abelian site sum, read EXACTLY (mod 2, unnormalised) -------
    blk11 = [0, 0, 0, 1]                      # w=2 indicator of the block 11
    cands.append(("AB_Z2_block11_exact", make_mod2_sum(2, blk11), "exact"))
    mono3 = [0, 0, 0, 0, 0, 0, 0, 1]          # w=3 monomial v0 v1 v2
    cands.append(("AB_Z2_monomial3_exact", make_mod2_sum(3, mono3), "exact"))

    # --- the same, read as a NORMALISED real density (a14 section 2.2) ----
    cands.append(("AB_density_normalised", make_density(2, blk11), "real"))
    cands.append(("AB_monomial3_normalised", make_density(3, mono3), "real"))

    print(json.dumps({"T": T, "cells": int(A.size),
                      "cells_changed_A_to_B": ndiff,
                      "fraction_changed": round(ndiff / A.size, 8),
                      "metric": "disagree(W) = fraction of rows t in [T/2,T) "
                                "with Q(A_t) != Q(B_t); for 'real' quantities "
                                "absAB = mean |Q(A_t) - Q(B_t)| as in a14"}),
          flush=True)

    rows = range(T // 2, T + 1)
    for W in (32, 64, 128, 256):
        half = W // 2
        out = {"W": W}
        for name, fn, kind in cands:
            va = [fn(A[t, B - half:B + half + 1]) for t in rows]
            vb = [fn(Bg[t, B - half:B + half + 1]) for t in rows]
            vc = [fn(C[t, B - half:B + half + 1]) for t in rows]
            dis = sum(1 for x, y in zip(va, vb) if x != y) / len(va)
            rec = {"disagreeAB": round(dis, 6),
                   "disagreeAC": round(sum(1 for x, y in zip(va, vc)
                                           if x != y) / len(va), 6),
                   "distinct_values_A": len(set(va))}
            if kind == "real":
                rec["absAB"] = float(f"{np.mean([abs(x - y) for x, y in zip(va, vb)]):.4g}")
            out[name] = rec
        out["s0_control_harness"] = {
            "A": round(disc.s0_control(A, B, W), 6),
            "B": round(disc.s0_control(Bg, B, W), 6),
            "absAB": round(abs(disc.s0_control(A, B, W)
                               - disc.s0_control(Bg, B, W)), 6)}
        print(json.dumps(out), flush=True)


if __name__ == "__main__":
    main()
