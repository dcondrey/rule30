def windows(bits, w):
    """Window indices (big-endian within the window) for a padded bit list."""
    out = []
    for x in range(len(bits) - w + 1):
        v = 0
        for j in range(w):
            v = (v << 1) | bits[x + j]
        out.append(v)
    return out


def nonzero_windows(bits, w):
    """Window indices with the all-zero window dropped (phi(0^w) = identity)."""
    return tuple(v for v in windows(bits, w) if v)


def product(ws, phi, mul, n):
    r = 0
    for v in ws:
        r = mul[r * n + phi[v]]
    return r


def _selftest():
    import logging

    logging.basicConfig(level=logging.INFO, format="%(message)s")
    reg = registry()
    for name, m in reg.items():
        m.check()
        logging.info(
            "%-10s n=%2d commutative=%-5s group=%s",
            name,
            m.n,
            m.is_commutative,
            m.is_group,
        )
    assert reg["T2"].n == 4 and reg["T3"].n == 27 and reg["S3"].n == 6
    assert not reg["S3"].is_commutative and not reg["T3"].is_commutative
    assert not reg["FlipFlop3"].is_commutative
    assert reg["T2"].is_commutative is False
    assert nonzero_windows([0, 0, 1, 1, 0, 0], 2) == (1, 3, 2)
    logging.info("OK: %d monoids, all axioms verified", len(reg))


if __name__ == "__main__":
    _selftest()
