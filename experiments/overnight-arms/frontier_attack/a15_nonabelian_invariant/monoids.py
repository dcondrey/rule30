"""Small finite monoids, and the sliding-block monoid-product functional.

Element 0 is ALWAYS the identity.  Multiplication is stored as a flat list
`mul` with `mul[a * n + b] = a*b`.

Composition convention for transformation monoids `T_k`: an element is a tuple
`t` of length `k` meaning `i -> t[i]`, and the product is "apply a, then b":
`(a*b)[i] = b[a[i]]`.  With that convention the left-to-right product along a
row is the composition of the row's local transformations in reading order,
i.e. exactly a finite automaton reading the row from left to right.

Validation: `python monoids.py` checks associativity, identity, and the group
axioms where claimed, for every monoid built here.
"""

from __future__ import annotations

import itertools


class Monoid:
    __slots__ = ("name", "n", "mul", "elems", "is_group", "is_commutative")

    def __init__(self, name, elems, mul):
        self.name = name
        self.elems = elems
        self.n = len(elems)
        self.mul = mul
        self.is_commutative = all(
            mul[a * self.n + b] == mul[b * self.n + a]
            for a in range(self.n)
            for b in range(self.n)
        )
        inv = {mul[a * self.n + b] for a in range(self.n) for b in range(self.n)}
        self.is_group = all(
            any(mul[a * self.n + b] == 0 for b in range(self.n)) for a in range(self.n)
        ) and len(inv) <= self.n

    def check(self):
        n, mul = self.n, self.mul
        for a in range(n):
            assert mul[0 * n + a] == a and mul[a * n + 0] == a, (self.name, "identity")
        for a in range(n):
            for b in range(n):
                ab = mul[a * n + b]
                for c in range(n):
                    assert mul[ab * n + c] == mul[a * n + mul[b * n + c]], (
                        self.name,
                        "associativity",
                    )
        return True

    def submonoid_generated(self, gens):
        """Index set of the submonoid generated by `gens` (identity included)."""
        n, mul = self.n, self.mul
        seen = {0}
        frontier = [0] + list(gens)
        seen.update(gens)
        while frontier:
            a = frontier.pop()
            for b in list(seen):
                for p in (mul[a * n + b], mul[b * n + a]):
                    if p not in seen:
                        seen.add(p)
                        frontier.append(p)
        return seen

    def sub_is_commutative(self, idxs):
        n, mul = self.n, self.mul
        return all(mul[a * n + b] == mul[b * n + a] for a in idxs for b in idxs)


def _from_tuples(name, elems):
    """Build a transformation monoid from an explicit closed set of tuples."""
    idx = {e: i for i, e in enumerate(elems)}
    n = len(elems)
    mul = [0] * (n * n)
    for a, ea in enumerate(elems):
        for b, eb in enumerate(elems):
            comp = tuple(eb[ea[i]] for i in range(len(ea)))  # apply a then b
            mul[a * n + b] = idx[comp]
    return Monoid(name, elems, mul)


def full_transformation(k):
    ident = tuple(range(k))
    elems = [ident] + sorted(e for e in itertools.product(range(k), repeat=k) if e != ident)
    return _from_tuples(f"T{k}", elems)


def symmetric(k):
    ident = tuple(range(k))
    elems = [ident] + sorted(p for p in itertools.permutations(range(k)) if p != ident)
    return _from_tuples(f"S{k}", elems)


def cyclic(m):
    elems = list(range(m))
    mul = [(a + b) % m for a in range(m) for b in range(m)]
    return Monoid(f"Z{m}", elems, mul)


def klein4():
    elems = [(0, 0), (0, 1), (1, 0), (1, 1)]
    idx = {e: i for i, e in enumerate(elems)}
    mul = [0] * 16
    for a, ea in enumerate(elems):
        for b, eb in enumerate(elems):
            mul[a * 4 + b] = idx[((ea[0] + eb[0]) % 2, (ea[1] + eb[1]) % 2)]
    return Monoid("Z2xZ2", elems, mul)


def flip_flop():
    """The 3-element flip-flop monoid {1, r0, r1}: r_i absorbs on the left.

    A canonical non-commutative, non-group monoid: the product of a word is
    its LAST non-identity letter.  Included because it is the cheapest
    'end-reader' and so is a deliberate positive control for that triviality.
    """
    elems = ["1", "r0", "r1"]
    mul = [0, 1, 2, 0, 1, 2, 0, 1, 2]
    mul[0], mul[1], mul[2] = 0, 1, 2
    for a in (1, 2):
        for b in range(3):
            mul[a * 3 + b] = b if b != 0 else a
    return Monoid("FlipFlop3", elems, mul)


def all_groups_upto6():
    """Complete list of groups of order <= 6 up to isomorphism."""
    return [
        cyclic(1),
        cyclic(2),
        cyclic(3),
        cyclic(4),
        klein4(),
        cyclic(5),
        cyclic(6),
        symmetric(3),
    ]


def registry():
    ms = all_groups_upto6() + [
        full_transformation(2),
        full_transformation(3),
        flip_flop(),
    ]
    return {m.name: m for m in ms}


