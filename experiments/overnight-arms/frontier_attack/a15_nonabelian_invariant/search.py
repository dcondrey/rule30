from monoids import nonzero_windows, registry  # noqa: E402
from substrate import lone_seed_rows, random_finite_config, step  # noqa: E402

args_finds_cap = [40]  # raised via --finds-cap; how many strict finds to store


def pad(bits, w):
    """Background margin wide enough that every window meeting the support is
    generated.  `w+1` zeros a side suffices for width-`w` windows."""
    k = w + 1
    return [0] * k + list(bits) + [0] * k


# ------------------------------------------------------------------ the bank


def build_bank(rule, w, rng, n_random=260, n_orbit=45, n_union=60):
    """(windows(s), windows(F s)) pairs, cheapest first so early exit is cheap.

    Composition:
      * random finite-support configurations of width 3..16 (the bulk);
      * consecutive rows of the lone-seed orbit (the class the register cares
        about);
      * disjoint unions of two random configs separated by w+2 zeros, which is
        what exercises the homomorphism lemma.
    """
    pairs = []
    for _ in range(n_random):
        width = rng.randint(3, 16)
        s = random_finite_config(rng, width)
        pairs.append((s, step(s, rule)))
    rows = lone_seed_rows(n_orbit, rule)
    for t in range(n_orbit - 1):
        pairs.append((rows[t][0], rows[t + 1][0]))
    for _ in range(n_union):
        a = random_finite_config(rng, rng.randint(3, 8))
        b = random_finite_config(rng, rng.randint(3, 8))
        s = a + [0] * (w + 2) + b
        pairs.append((s, step(s, rule)))
    pairs.sort(key=lambda p: len(p[0]))
    return [(nonzero_windows(pad(s, w), w), nonzero_windows(pad(t, w), w))
            for s, t in pairs]


def build_orbit(rule, w, n=60):
    rows = lone_seed_rows(n, rule)
    return [nonzero_windows(pad(r[0], w), w) for r in rows]


def build_interior_probes(rule, w, rng, n=90):
    """(base, flipped) config pairs differing at one INTERIOR cell only."""
    out = []
    for _ in range(n):
        width = rng.randint(2 * w + 5, 2 * w + 14)
        s = random_finite_config(rng, width)
        s[0] = 1
        s[-1] = 1
        p = rng.randrange(w + 1, width - w - 1)
        t = list(s)
        t[p] ^= 1
        out.append((nonzero_windows(pad(s, w), w), nonzero_windows(pad(t, w), w)))
    return out


# ------------------------------------------------------------------ the gates


def phi_value(ws, phi, mul, n):
    r = 0
    for v in ws:
        r = mul[r * n + phi[v]]
    return r


def test_candidate(phi, mon, bank, orbit, probes):
    """Returns (survived, record).  Early-exits on the first conflict."""
    n, mul = mon.n, mon.mul
    f = {}
    for ws_s, ws_t in bank:
        a = phi_value(ws_s, phi, mul, n)
        b = phi_value(ws_t, phi, mul, n)
        prev = f.get(a, b)
        if prev != b:
            return False, None
        f[a] = b
    orb = [phi_value(ws, phi, mul, n) for ws in orbit]
    image = set(f) | set(f.values()) | set(orb)
    rec = {
        "f": {str(k): v for k, v in sorted(f.items())},
        "image": sorted(image),
        "orbit_head": orb[:24],
        "T1_constant": len(image) == 1,
        "T2_orbit_flat": len(set(orb[len(orb) // 3:])) == 1,
    }
    rec["T3_end_reader"] = all(
        phi_value(a, phi, mul, n) == phi_value(b, phi, mul, n) for a, b in probes)
    sub = mon.submonoid_generated([x for x in phi if x != 0])
    rec["T4_commutative_image"] = mon.sub_is_commutative(sub)
    rec["submonoid_size"] = len(sub)
    # derived lemma: f must be a homomorphism on the image
    homs, bad = 0, 0
    for x in image:
        for y in image:
            xy = mul[x * n + y]
            if x in f and y in f and xy in f:
                homs += 1
                if f[xy] != mul[f[x] * n + f[y]]:
                    bad += 1
    rec["hom_checks"] = homs
    rec["hom_violations"] = bad
    # `nontrivial` = interior-sensitive and non-constant.  `nontrivial_strict`
    # additionally demands the lone-seed orbit not be eventually constant.
    # Both are reported: the saturation controls (rules 204/170) have a frozen
    # lone-seed orbit by construction, so they can only ever clear the former.
    # A homomorphism violation is a PROOF of non-conservation (the lemma is
    # derived, not assumed), so it disqualifies the candidate outright: it is a
    # false survivor the bank happened not to kill.
    rec["verified"] = bad == 0
    rec["nontrivial"] = rec["verified"] and not (rec["T1_constant"]
                                                 or rec["T3_end_reader"])
    rec["nontrivial_strict"] = rec["nontrivial"] and not rec["T2_orbit_flat"]
    return True, rec


# ---------------------------------------------------------------- enumeration


def enumerate_phi(mon, w, budget, rng):
    """Exhaustive when |M|^(2^w - 1) <= budget, otherwise uniform sampling.

    Returns (iterator, mode, count).
    """
    k = (1 << w) - 1
    total = mon.n ** k
    if total <= budget:
        def gen():
            for tail in itertools.product(range(mon.n), repeat=k):
                yield (0,) + tail
        return gen(), "exhaustive", total

    def gen():
        for _ in range(budget):
            yield (0,) + tuple(rng.randrange(mon.n) for _ in range(k))
    return gen(), "sampled", budget


def run(rule, mon, w, budget, seed, out):
    rng = random.Random(seed)
    bank = build_bank(rule, w, rng)
    orbit = build_orbit(rule, w)
    probes = build_interior_probes(rule, w, rng)
    it, mode, count = enumerate_phi(mon, w, budget, random.Random(seed + 7))
    t0 = time.time()
    tally = {"survivors": 0, "T1_constant": 0, "T2_orbit_flat": 0,
             "T3_end_reader": 0, "T4_commutative_image": 0,
             "hom_violations": 0, "verified_survivors": 0,
             "nontrivial": 0, "nontrivial_strict": 0}
    finds = []
    for phi in it:
        ok, rec = test_candidate(phi, mon, bank, orbit, probes)
        if not ok:
            continue
        tally["survivors"] += 1
        for key in ("T1_constant", "T2_orbit_flat", "T3_end_reader",
                    "T4_commutative_image"):
            tally[key] += int(rec[key])
        tally["hom_violations"] += int(rec["hom_violations"] > 0)
        tally["verified_survivors"] += int(rec["verified"])
        tally["nontrivial"] += int(rec["nontrivial"])
        if rec["nontrivial_strict"]:
            tally["nontrivial_strict"] += 1
            if len(finds) < args_finds_cap[0]:
                finds.append({"phi": list(phi), **rec})
    row = {"rule": rule, "monoid": mon.name, "monoid_size": mon.n,
           "commutative_monoid": mon.is_commutative, "is_group": mon.is_group,
           "w": w, "mode": mode, "candidates": count,
           "bank_pairs": len(bank), "orbit_rows": len(orbit),
           "interior_probes": len(probes),
           "seconds": round(time.time() - t0, 2), **tally,
           "finds": finds}
    out.write(json.dumps(row) + "\n")
    out.flush()
    print(json.dumps({k: v for k, v in row.items() if k != "finds"}), flush=True)
    return row


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=f"{HERE}/results.jsonl")
    ap.add_argument("--budget", type=int, default=300000)
    ap.add_argument("--seed", type=int, default=20260830)
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--rules", default="30,90")
    ap.add_argument("--monoids", default="")
    ap.add_argument("--widths", default="")
    ap.add_argument("--finds-cap", type=int, default=40,
                    help="max strictly-nontrivial candidates stored per cell")
    ap.add_argument("--append", action="store_true",
                    help="append to --out instead of truncating it")
    args = ap.parse_args()

    args_finds_cap[0] = args.finds_cap
    reg = registry()
    names = (args.monoids.split(",") if args.monoids else
             ["Z2", "Z3", "Z4", "Z2xZ2", "Z5", "Z6", "S3", "T2", "T3",
              "FlipFlop3"])
    widths = ([int(x) for x in args.widths.split(",")] if args.widths
              else ([1, 2, 3] if args.quick else [1, 2, 3, 4, 5, 6]))
    rules = [int(x) for x in args.rules.split(",")]
    with open(args.out, "a" if args.append else "w") as out:
        for rule in rules:
            for name in names:
                for w in widths:
                    run(rule, reg[name], w, args.budget, args.seed, out)


if __name__ == "__main__":
    main()
