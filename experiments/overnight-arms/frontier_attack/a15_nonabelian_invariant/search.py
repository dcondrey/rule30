"""Bounded search for a NON-ABELIAN transfer invariant of Rule 30.

OBJECT (pre-registered, exactly as searched)
--------------------------------------------
Fix a finite monoid `M` with identity `e`, a window width `w`, and a map
`phi: {0,1}^w -> M` with `phi(0^w) = e`.  For a finite-support configuration
`s` over a quiescent background, define the ordered product

    Phi(s) = phi(s[x .. x+w-1])  for x = -inf .. +inf, multiplied LEFT TO RIGHT

which is a finite product in `M` because all but finitely many factors are `e`.

`Phi` is a TRANSFER INVARIANT iff there is a function `f: M -> M` with

    Phi(F(s)) = f(Phi(s))   for every finite-support `s`,      (*)

`F` the rule's global map.  `f` is not stipulated: it is *reconstructed* from
the data as a partial function on the observed image, and (*) fails the moment
two configurations with the same `Phi` have successors with different `Phi`.
This subsumes "invariant" (`f = id`), "invariant up to a twist" (`f` an
automorphism) and "invariant up to conjugation" (`f = x -> g x g^-1`).

DERIVED LEMMA (not assumed; verified in code for every survivor).  If `s` and
`s'` have supports separated by more than `w` cells, then
`Phi(s u s') = Phi(s) Phi(s')`, and after one step the two light cones are
still separated by more than `w`, so (*) forces
`f(Phi(s) Phi(s')) = f(Phi(s)) f(Phi(s'))`: **f must be a homomorphism on the
image submonoid.**  Anti-homomorphisms are therefore excluded unless the image
is commutative.  The search does not use this to prune; it uses it as an
independent consistency check, and disjoint-union pairs are put in the bank so
the constraint is exercised.

TRIVIALITY LADDER (pre-registered before running; a "find" must clear all of
it):
  T1 constant      -- |image| = 1, i.e. Phi == e.  Coboundaries
                      `phi(v) = g(v_0..v_{w-2}) g(v_1..v_{w-1})^{-1}` in a
                      group telescope to `e` on finite support and land here.
  T2 orbit-flat    -- Phi(row_t) eventually constant along the lone-seed orbit,
                      so it carries no per-row information.  (An absorbing
                      zero in the image turns Phi into "does the row contain
                      word v", which is eventually constant.)
  T3 end-reader    -- flipping interior cells, more than `w` from both ends of
                      the support, never moves Phi.  A rank-1 (constant)
                      element in the image absorbs one side and produces this;
                      such a Phi is column-blind and dies at step 0 anyway.
  T4 commutative   -- the submonoid generated by the image is commutative, so
                      the object is an abelian site sum in disguise.  Bucketed
                      separately rather than discarded: a14 covers Z/2 and Z/3,
                      so a commutative find in Z/4, Z/5, Z/6 or Z/2xZ/2 would
                      still be new, while one in Z/2 or Z/3 would contradict
                      a14 and indicate a bug.

The Rule 90 filter (PATH.md section 0) is applied by running the identical
search for Rule 90 and reporting both columns.

USAGE
    uv run python search.py --out results.jsonl [--quick]
"""

from __future__ import annotations

