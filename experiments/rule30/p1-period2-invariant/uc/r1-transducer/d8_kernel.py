#!/usr/bin/env python3
"""D8 cocycle coordinates for the column map, verified against psi_kernel.

Everything here is derived from BRIEF section 2 and then checked against the
kernel table CONE (phi) and the forced runs of the rotated wedge.

Coordinates.  A cell T in {0..3} has state x = (h, F) with h = T >> 1 and
F = E = 1 + h + Lo(T) mod 2.  The letter action of a cell l on the next
column's state is lam(l) in D8, where D8 is the affine group of Z_2^2
generated by

    t : (h, F) -> (h + 1, F)          translation
    s : (h, F) -> (h, F + h)          shear

and an element is written g = T_v s^eps with v in Z_2^2, eps in Z_2:
g(x) = v + s^eps(x).  Composition: (T_v s^e)(T_w s^f) = T_{v + s^e w} s^{e+f}.

Claim (i):   phi(l, r) = lam(l) . r  for all 16 pairs, with
             lam(1) = lam(3) = t, lam(0) = s, lam(2) = t s.
Claim (ii):  along a forced run T[u][n] = c for u >= n, the forced endpoint
             state y_{u+1} = (H(e_{u+1}), E(e_{u+1})) equals t . G_u^{-1} . x_c
             where G_u = lam(T[u][n-1]) ... lam(T[u][-u-1]) is the holonomy of
             column u from its top cell (the endpoint symbol) to depth n-1,
             and x_c = state(c).
Claim (iii): Stab(x_2) = Stab(x_3) = {id, sigma}, sigma = T_(0,1) s.
Claim (iv):  the binary condition E(e_{u+1}) = 0 is G_u in A_c with
             A_2 = {id, t, ts, sigma}, A_3 = {T_(0,1), T_(1,1), s, T_(1,1) s},
             both unions of right cosets Stab . g.
"""

from __future__ import annotations

import sys
from itertools import product

sys.path.insert(0, "/Volumes/A/researchpapers/13-rule30/experiments/rule30/p1-period2-invariant")

from psi_kernel import CONE, Endpoint  # noqa: E402


# ---------- states and cells ----------

def state(cell: int) -> tuple[int, int]:
    h = cell >> 1
    lo = cell & 1
    return (h, (1 + h + lo) & 1)


def cell_of(x: tuple[int, int]) -> int:
    h, f = x
    lo = (1 + h + f) & 1
    return 2 * h + lo


# ---------- D8 as (v1, v2, eps) ----------

G = tuple[int, int, int]  # (v1, v2, eps)
ID: G = (0, 0, 0)
T10: G = (1, 0, 0)  # t
T01: G = (0, 1, 0)
T11: G = (1, 1, 0)
S: G = (0, 0, 1)  # s


def shear(x: tuple[int, int], e: int) -> tuple[int, int]:
    h, f = x
    return (h, (f + e * h) & 1) if e else (h, f)


def act(g: G, x: tuple[int, int]) -> tuple[int, int]:
    v1, v2, e = g
    h, f = shear(x, e)
    return ((h + v1) & 1, (f + v2) & 1)


def mul(g: G, k: G) -> G:
    """g . k  (apply k first, then g)."""
    v1, v2, e = g
    w1, w2, f = k
    sw = shear((w1, w2), e)
    return ((v1 + sw[0]) & 1, (v2 + sw[1]) & 1, (e + f) & 1)


def inv(g: G) -> G:
    v1, v2, e = g
    # g^{-1} = s^e T_v  = T_{s^e v} s^e
    sv = shear((v1, v2), e)
    return (sv[0], sv[1], e)


TS: G = mul(T10, S)
SIGMA: G = mul(T01, S)

LAM = {1: T10, 3: T10, 0: S, 2: TS}

D8 = [(a, b, c) for a in (0, 1) for b in (0, 1) for c in (0, 1)]

NAMES = {
    ID: "id", T10: "t", T01: "T01", T11: "T11", S: "s",
    TS: "ts", SIGMA: "sigma", mul(T11, S): "T11s",
}


def holonomy(cells: list[int]) -> G:
    """Product lam(cells[-1]) ... lam(cells[0]) : first cell acts first."""
    g = ID
    for c in cells:
        g = mul(LAM[c], g)
    return g


def check_group() -> None:
    for g in D8:
        for k in D8:
            for x in product((0, 1), repeat=2):
                assert act(mul(g, k), x) == act(g, act(k, x)), (g, k, x)
        assert mul(g, inv(g)) == ID and mul(inv(g), g) == ID, g
    assert len({mul(g, k) for g in D8 for k in D8}) == 8
    print("D8: composition and inverse consistent, closed, order 8")


def check_phi() -> int:
    n = 0
    for l in range(4):
        for r in range(4):
            assert cell_of(act(LAM[l], state(r))) == CONE[l][r], (l, r)
            n += 1
    print(f"claim (i): phi(l,r) = lam(l).r on all {n} pairs")
    return n


def check_stabilisers() -> None:
    for c in (2, 3):
        xc = state(c)
        stab = [g for g in D8 if act(g, xc) == xc]
        assert sorted(stab) == sorted([ID, SIGMA]), (c, stab)
    print("claim (iii): Stab(x_2) = Stab(x_3) = {id, sigma}, sigma = T01 s")


def allowed_set(c: int) -> list[G]:
    xc = state(c)
    return [g for g in D8 if act(inv(g), xc)[1] == 0]


def check_allowed() -> None:
    a2 = allowed_set(2)
    a3 = allowed_set(3)
    assert sorted(a2) == sorted([ID, T10, TS, SIGMA]), a2
    assert sorted(a3) == sorted([T01, T11, S, mul(T11, S)]), a3
    for a in (a2, a3):
        for g in a:
            assert mul(SIGMA, g) in a
    print("claim (iv): A_2 = {id,t,ts,sigma}, A_3 = {T01,T11,s,T11s}; both Stab-right-coset unions")


def column_cells(ep: Endpoint) -> list[int]:
    """Cells of the last column from its top (endpoint symbol) to its bottom."""
    u = ep.length - 1
    # column[j] = T[u][-j] for j <= u, column[u+1] = e_u
    top = [ep.column[j] for j in range(u + 1, -1, -1)]  # depths -u-1 .. 0
    return top + list(ep.diagonal[1:])  # depths 1 .. u


def check_forced_runs(max_n: int) -> tuple[int, int]:
    """Claim (ii) on every binary W, both c, every forced step, n <= max_n."""
    checks = 0
    runs = 0
    for n in range(1, max_n + 1):
        for c in (2, 3):
            xc = state(c)
            for W in product((1, 2), repeat=n):
                ep = Endpoint()
                for s in W:
                    ep.append(s)
                runs += 1
                for _ in range(n + 2):
                    u = ep.length - 1
                    cells = column_cells(ep)  # depths -u-1 .. u
                    window = cells[: (n - 1) - (-u - 1) + 1]  # depths -u-1 .. n-1
                    assert len(window) == n + u + 1
                    g = holonomy(window)
                    y = act(T10, act(inv(g), xc))
                    e_next = cell_of(y)
                    # the kernel's forced symbol: unique 4-state symbol with T[u+1][n] == c
                    forced = [sym for sym in range(4) if ep.peek(sym)[1][n] == c]
                    assert forced == [e_next], (n, c, W, u, forced, e_next)
                    checks += 1
                    ep.append(e_next)
    print(f"claim (ii): forced 4-state symbol = t.G_u^-1.x_c on {checks} column steps, {runs} runs")
    return checks, runs


def main() -> None:
    check_group()
    check_phi()
    check_stabilisers()
    check_allowed()
    check_forced_runs(9)


if __name__ == "__main__":
    main()
